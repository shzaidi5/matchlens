LANGUAGES: dict[str, dict[str, str]] = {"en": EN, "es": ES}
LANGUAGE_NAMES = {"en": "English", "es": "Spanish", "fr": "French", "pt": "Portuguese", "ar": "Arabic", "ja": "Japanese", "hi": "Hindi", "de": "German"}


def has_language(lang: str) -> bool:
    return lang in LANGUAGES


def fmt_value(value: Any, lang: str) -> str:
    """Numbers as a reader of `lang` expects them (decimal comma in Spanish)."""
    if isinstance(value, bool):
        return str(value)
    if isinstance(value, float):
        text = f"{value:g}"
        return text.replace(".", ",") if lang == "es" else text
    return str(value)


class _Facts(dict):
    """format_map helper that remembers whether a placeholder had no fact."""

    def __init__(self, *args: Any, **kwargs: Any) -> None:
        super().__init__(*args, **kwargs)
        self.missing = False

    def __missing__(self, name: str) -> str:
        self.missing = True
        return ""


def render(template: str, facts: dict[str, Any], lang: str) -> str | None:
    """Fill a template, or return None if any fact it needs is missing or None."""
    values = _Facts({k: fmt_value(v, lang) for k, v in facts.items() if v is not None})
    text = template.format_map(values)
    return None if values.missing else text


def tr(lang: str, key: str, facts: dict[str, Any] | None = None) -> str | None:
    """Render one template, or None if the key or any fact it needs is missing.

    Returning None (rather than printing a hole) lets the narrator simply skip
    a sentence it cannot fully support.
    """
    template = LANGUAGES.get(lang, EN).get(key)
    if template is None:
        return None
    return render(template, facts or {}, lang)
